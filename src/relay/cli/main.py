@app.command()
def status(swarm: str = SwarmOpt) -> None:
    """Ledger depth, DLQ depth, live presence."""
    name = _swarm(swarm)
    client = get_client()
    entries = client.xlen(ledger_key(name))
    dead = dlq_mod.dlq_depth(client, name)
    console.print(f"swarm '{name}'   ledger: {entries} entries   "
                  f"dlq: {'[red]' if dead else ''}{dead}{'[/red]' if dead else ''}")
    live = sorted(str(k) for k in client.scan_iter(match=presence_key(name, "*", "*")))
    if live:
        console.print("live workers:")
        for key in live:
            console.print(f"  • {key.rsplit(':', 1)[-1]}")
    else:
        console.print("live workers: none")


@app.command()
def audit(swarm: str = SwarmOpt) -> None:
    """Re-validate the whole ledger against the contract. Exit 1 on findings."""
    name = _swarm(swarm)
    report = audit_ledger(get_client(), ContractValidator(load_contract()), name)
    if report.ok:
        console.print(f"[green]✓[/green] {report.entries} entries, no findings")
        raise typer.Exit(0)
    table = Table(title=f"Audit findings — swarm '{name}' ({report.entries} entries)")
    table.add_column("seq")
    table.add_column("rule")
    table.add_column("detail")
    for f in report.findings:
        table.add_row(str(f.seq), f.rule, f.detail)
    console.print(table)
    raise typer.Exit(1)


