@app.command()
def init(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    test_command: str = typer.Option(
        "uv run pytest -q {test_paths}", "--test-command",
        help="How the toolgate runs acceptance tests (use {test_paths})",
    ),
) -> None:
    """Prepare a project without starting it (relay up does this automatically)."""
    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    _initialize(project, swarm or project.name, test_command)


# ── runtime ───────────────────────────────────────────────────────────────────

@app.command()
def up(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    roles: str = typer.Option("", "--roles", help="Comma-separated subset (default: all Phase-1 roles)"),
    tmux: bool = typer.Option(False, "--tmux", help="Open a tmux session: watch + per-role tails"),
    windows: bool = typer.Option(False, "--windows",
                                 help="Open one Terminal window per assistant (live activity) + watch"),
) -> None:
    """Start the swarm for a project (initializing it on first run)."""
    from relay.cli import procs, redisctl

    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    from relay.cli.context import has_config

    legacy_config = project / "relay.toml"
    if legacy_config.is_file() and not (project / ".relay" / "relay.toml").exists():
        (project / ".relay").mkdir(exist_ok=True)
        legacy_config.rename(project / ".relay" / "relay.toml")
        console.print("[green]✓[/green] moved relay.toml → .relay/relay.toml (root stays clean)")
    if not has_config(project):
        _initialize(project, swarm or project.name, "uv run pytest -q {test_paths}")
    name = swarm or swarm_name(project)

    from relay.bus import groups as groups_mod
    from relay.bus.keys import group_name, ledger_key
    from relay.cli.profiles import write_profiles

    console.print(f"[green]✓[/green] {redisctl.ensure_running(procs.state_root())}")
    if not _claim_swarm(name, project):
        raise typer.Exit(1)
    write_profiles(project, name)  # keep permission profiles + hooks current
    for role in ("interpreter", "owner"):  # interpreter mail queues even before chat opens
        groups_mod.ensure_group(get_client(), ledger_key(name), group_name(role))
    selected = [r.strip() for r in roles.split(",") if r.strip()]
    if not selected:
        from relay.coordinator.policy import Policy
        from relay.workers.run import resolve_policy_path

        selected = list(procs.PHASE1_ROLES)
        policy_path = resolve_policy_path(project)
        if policy_path is not None:
            policy = Policy.load(policy_path)
            for spec in (*policy.per_behaviour, *policy.per_story, *policy.per_iteration):
                if spec.role not in selected:
                    selected.append(spec.role)
    for role in selected:
        pid = procs.start_worker(name, role, project)
        console.print(f"[green]✓[/green] {role} (pid {pid})")
    console.print(f"\nswarm '[bold]{name}[/bold]' is up — next, in this folder:")
    console.print("  relay chat     (terminal 1 — talk to the swarm)")
    console.print("  relay watch    (terminal 2 — live board)")
    if tmux:
        _open_tmux(name, selected)
    if windows:
        import tomllib

        from relay.cli.context import config_path

        ui_cfg = tomllib.loads(config_path(project).read_text()).get("ui") or {}
        _open_windows(name, selected, terminal=str(ui_cfg.get("terminal", "iterm")))


def _claim_swarm(name: str, project: Path) -> bool:
    """Two folders with the same basename must not share a ledger: a swarm
    name belongs to exactly one project directory."""
    from relay.bus.keys import project_key

    client = get_client()
    raw_owner = client.get(project_key(name))
    owner = raw_owner.decode() if isinstance(raw_owner, bytes) else raw_owner
    if owner and str(owner) != str(project):
        console.print(
            f"[red]✗[/red] swarm '{name}' already belongs to {owner}.\n"
            f"  Give this project its own name:  relay up . --swarm {name}-2\n"
            f"  (or set it permanently under [swarm] name in relay.toml)"
        )
        return False
    client.set(project_key(name), str(project))
    return True


def _open_windows(name: str, roles: list[str], terminal: str = "iterm") -> None:
    """One read-only viewer window per assistant + one mission-control watch.

    Viewers only: they follow logs and the stream, deliver nothing, and can be
    closed at any time without affecting the swarm. The terminal app comes
    from [ui] terminal in relay.toml — iTerm by default.
    """
    import platform

    import shutil as _shutil

    if platform.system() != "Darwin":
        console.print("[yellow]•[/yellow] --windows is macOS-only — use --tmux here")
        return
    # iTerm runs the command DIRECTLY (no shell, bare launchd PATH), so use the
    # absolute relay path and wrap in a login shell for the user's environment
    relay_bin = _shutil.which("relay") or "relay"
    commands = [f"{relay_bin} watch --swarm {name}"] + [
        f"{relay_bin} tail {r} --swarm {name}" for r in roles
    ]

    def _iterm(command: str) -> bool:
        shell_command = f"/bin/zsh -lc '{command}'"
        script = (f'tell application "iTerm"\n'
                  f'  create window with default profile command "{shell_command}"\n'
                  f'end tell')
        return sp.run(["osascript", "-e", script], capture_output=True).returncode == 0

    def _terminal_app(command: str) -> bool:
        return sp.run(["osascript", "-e",
                       f'tell application "Terminal" to do script "{command}"'],
                      capture_output=True).returncode == 0

    open_one = _iterm if terminal.lower() in ("iterm", "iterm2") else _terminal_app
    app_name = "iTerm" if open_one is _iterm else "Terminal"
    opened = 0
    for command in commands:
        if not open_one(command):
            if open_one is _iterm:  # iTerm missing/unscriptable → fall back once, loudly
                console.print("[yellow]•[/yellow] iTerm not reachable — falling back to Terminal.app "
                              '(set [ui] terminal = "terminal" in relay.toml to silence this)')
                open_one, app_name = _terminal_app, "Terminal"
                if open_one(command):
                    opened += 1
                continue
        else:
            opened += 1
    sp.run(["osascript", "-e", f'tell application "{app_name}" to activate'], capture_output=True)
    console.print(f"[green]✓[/green] {opened} {app_name} windows opened (read-only viewers)")


def _open_tmux(name: str, roles: list[str]) -> None:
    import shutil as _shutil

    if _shutil.which("tmux") is None:
        console.print("[yellow]•[/yellow] tmux not installed — skipping --tmux")
        return
    session = f"relay-{name}"
    sp.run(["tmux", "kill-session", "-t", session], capture_output=True)
    sp.run(["tmux", "new-session", "-d", "-s", session, "-n", "watch",
            f"relay watch --swarm {name}"], check=True)
    sp.run(["tmux", "set-option", "-t", session, "mouse", "on"], capture_output=True)
    for role in roles:
        sp.run(["tmux", "new-window", "-t", session, "-n", role,
                f"relay tail {role} --swarm {name}"], check=True)
    sp.run(["tmux", "select-window", "-t", f"{session}:watch"], capture_output=True)
    console.print(f"[green]✓[/green] tmux session ready (mouse on):  tmux attach -t {session}")


@app.command()
def down(swarm: str = SwarmOpt) -> None:
    """Stop the enclosing project's swarm (the ledger keeps everything)."""
    from relay.cli import procs

    name = _swarm(swarm)
    stopped = False
    for role in list(procs.running_roles(name)) or list(procs.PHASE1_ROLES):
        if procs.stop_worker(name, role):
            console.print(f"[green]✓[/green] {role} stopped")
            stopped = True
    strays = procs.reap_swarm(name)  # zombies with no pidfile (deleted state dirs)
    if strays:
        console.print(f"[yellow]•[/yellow] reaped {len(strays)} untracked worker(s): "
                      f"{', '.join(map(str, strays))}")
    if stopped or strays:
        console.print(f"swarm '{name}' is down — `relay up` resumes exactly here")


