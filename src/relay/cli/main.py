"""The `relay` CLI.

Project-centric like git: `relay up <folder>` starts (auto-initializing on
first run); every other command finds the project by walking up from the
current directory. --swarm remains as an explicit override everywhere.
"""

from __future__ import annotations

import json
import subprocess as sp
from pathlib import Path

import typer
from rich.console import Console
from rich.table import Table

from relay import __version__
from relay.bus import dlq as dlq_mod
from relay.bus.client import get_client
from relay.bus.keys import ledger_key, presence_key
from relay.cli.context import NoProjectError, resolve_swarm, swarm_name
from relay.contract import ContractValidator, load_contract
from relay.contract.codegen import write_artifacts
from relay.ledger.audit import audit_ledger
from relay.ledger.export import export_jsonl

app = typer.Typer(no_args_is_help=True, help="Relay Agentic Framework")
contract_app = typer.Typer(no_args_is_help=True, help="Contract tooling")
app.add_typer(contract_app, name="contract")
console = Console()

SwarmOpt = typer.Option(None, "--swarm", help="Swarm name (default: the enclosing project's)")


def _swarm(explicit: str | None) -> str:
    try:
        return resolve_swarm(explicit)
    except NoProjectError as e:
        console.print(f"[red]✗[/red] {e}")
        raise typer.Exit(1) from None


@app.callback()
def _version_callback() -> None:
    """Relay Agentic Framework CLI."""


# ── contract tooling ──────────────────────────────────────────────────────────

@contract_app.command("gen")
def contract_gen() -> None:
    """Regenerate contract/schema/*.json and docs/PROTOCOL.md from the contract."""
    contract = load_contract()
    paths = write_artifacts(contract)
    console.print(f"[green]✓[/green] contract {contract.contract_hash[:12]} — {len(paths)} artifacts written")


@contract_app.command("show")
def contract_show() -> None:
    """Summarize the loaded contract."""
    c = load_contract()
    console.print(f"version {c.version}, hash [bold]{c.contract_hash}[/bold]")
    console.print(f"{len(c.message_types)} message types, {len(c.edges)} edges, planes: {', '.join(c.planes)}")


# ── project initialization (also invoked automatically by `relay up`) ────────

def _initialize(project: Path, swarm: str, test_command: str) -> None:
    from relay.cli.profiles import write_profiles

    if sp.run(["git", "rev-parse", "--git-dir"], cwd=project, capture_output=True).returncode != 0:
        sp.run(["git", "init", "-q", "-b", "main"], cwd=project, check=True)
        console.print("[green]✓[/green] git repository initialized")
    gitignore = project / ".gitignore"
    marker = ".relay/"
    if not gitignore.exists() or marker not in gitignore.read_text():
        with gitignore.open("a") as f:
            f.write(f"\n# relay swarm runtime state\n{marker}\n")
        console.print(f"[green]✓[/green] added {marker} to .gitignore")
    if sp.run(["git", "rev-parse", "HEAD"], cwd=project, capture_output=True).returncode != 0:
        sp.run(["git", "add", "-A"], cwd=project, check=True)
        sp.run(["git", "commit", "-qm", "Initial commit (relay init)"], cwd=project, check=True)
        console.print("[green]✓[/green] initial commit created")

    profiles = write_profiles(project)
    console.print(f"[green]✓[/green] {len(profiles)} permission profiles → {profiles[0].parent}")

    gates_src = Path(__file__).resolve().parents[3] / "policies" / "gates.yaml"
    gates_dst = project / ".relay" / "gates.yaml"
    if gates_src.exists() and not gates_dst.exists():
        gates_dst.parent.mkdir(parents=True, exist_ok=True)
        gates_dst.write_text(gates_src.read_text())
        console.print(f"[green]✓[/green] gate policy → {gates_dst}")

    config = project / "relay.toml"
    if config.exists():
        return
    config.write_text(
        "# Relay swarm configuration for this project\n"
        f"# generated by relay {__version__}\n\n"
        "[swarm]\n"
        f'name = "{swarm}"\n\n'
        "[commands]\n"
        f'acceptance_test = "{test_command}"\n'
        '# suite = "uv run pytest -q"\n\n'
        "[roles.interpreter]\n"
        'runner = "claude"\nmodel = "opus"\n\n'
        "[roles.analyst]\n"
        'runner = "claude"\n\n'
        "[roles.specifier]\n"
        'runner = "claude"\n\n'
        "[roles.builder]\n"
        'runner = "claude"\n'
    )
    console.print(f"[green]✓[/green] wrote {config}")


@app.command()
def init(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    test_command: str = typer.Option(
        "uv run pytest -q {test_paths}", "--test-command",
        help="How the toolgate runs acceptance tests (use {test_paths})",
    ),
) -> None:
    """Prepare a project without starting it (relay up does this automatically)."""
    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    _initialize(project, swarm or project.name, test_command)


# ── runtime ───────────────────────────────────────────────────────────────────

@app.command()
def up(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    roles: str = typer.Option("", "--roles", help="Comma-separated subset (default: all Phase-1 roles)"),
) -> None:
    """Start the swarm for a project (initializing it on first run)."""
    from relay.cli import procs, redisctl

    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    if not (project / "relay.toml").exists():
        _initialize(project, swarm or project.name, "uv run pytest -q {test_paths}")
    name = swarm or swarm_name(project)

    console.print(f"[green]✓[/green] {redisctl.ensure_running(procs.state_root())}")
    selected = [r.strip() for r in roles.split(",") if r.strip()]
    if not selected:
        from relay.coordinator.policy import Policy
        from relay.workers.run import resolve_policy_path

        selected = list(procs.PHASE1_ROLES)
        policy_path = resolve_policy_path(project)
        if policy_path is not None:
            policy = Policy.load(policy_path)
            for spec in (*policy.per_behaviour, *policy.per_story, *policy.per_iteration):
                if spec.role not in selected:
                    selected.append(spec.role)
    for role in selected:
        pid = procs.start_worker(name, role, project)
        console.print(f"[green]✓[/green] {role} (pid {pid})")
    console.print(f"\nswarm '[bold]{name}[/bold]' is up — next, in this folder:")
    console.print("  relay chat     (terminal 1 — talk to the swarm)")
    console.print("  relay watch    (terminal 2 — live board)")


@app.command()
def down(swarm: str = SwarmOpt) -> None:
    """Stop the enclosing project's swarm (the ledger keeps everything)."""
    from relay.cli import procs

    name = _swarm(swarm)
    stopped = False
    for role in list(procs.running_roles(name)) or list(procs.PHASE1_ROLES):
        if procs.stop_worker(name, role):
            console.print(f"[green]✓[/green] {role} stopped")
            stopped = True
    if stopped:
        console.print(f"swarm '{name}' is down — `relay up` resumes exactly here")


@app.command()
def chat(swarm: str = SwarmOpt) -> None:
    """A live Claude session with the Interpreter (streams replies, keeps context)."""
    import tomllib

    from relay.cli import procs
    from relay.cli.context import find_project
    from relay.cli.interpreter_session import InterpreterSession
    from relay.cli.profiles import settings_path

    project = find_project()
    name = _swarm(swarm)
    config = tomllib.loads((project / "relay.toml").read_text())
    roles_cfg = config.get("roles") or {}
    interp_cfg = roles_cfg.get("interpreter") or {}
    settings = settings_path(project, "interpreter")
    playbook = Path(__file__).resolve().parents[3] / "roles" / "interpreter.md"
    InterpreterSession(
        swarm=name,
        project=project,
        model=interp_cfg.get("model"),
        settings=settings if settings.exists() else None,
        playbook_path=playbook,
        state_dir=procs.state_root() / name / "interpreter",
    ).run()


@app.command()
def watch(swarm: str = SwarmOpt) -> None:
    """Live board: assistant liveness, behaviour states, event feed."""
    from relay.cli.watch import watch as watch_loop

    try:
        watch_loop(_swarm(swarm))
    except KeyboardInterrupt:
        pass


@app.command()
def tail(
    role: str = typer.Argument(..., help="Assistant role to follow"),
    swarm: str = SwarmOpt,
) -> None:
    """Follow one assistant's worker log."""
    import time as _time

    from relay.cli import procs

    log = procs.logfile(_swarm(swarm), role)
    console.print(f"[dim]{log}[/dim]")
    with log.open() as f:
        try:
            while True:
                line = f.readline()
                if line:
                    console.print(line.rstrip())
                else:
                    _time.sleep(0.5)
        except KeyboardInterrupt:
            pass


# ── observability / audit ─────────────────────────────────────────────────────

@app.command()
def status(swarm: str = SwarmOpt) -> None:
    """Ledger depth, DLQ depth, live presence."""
    name = _swarm(swarm)
    client = get_client()
    entries = client.xlen(ledger_key(name))
    dead = dlq_mod.dlq_depth(client, name)
    console.print(f"swarm '{name}'   ledger: {entries} entries   "
                  f"dlq: {'[red]' if dead else ''}{dead}{'[/red]' if dead else ''}")
    live = sorted(str(k) for k in client.scan_iter(match=presence_key(name, "*", "*")))
    if live:
        console.print("live workers:")
        for key in live:
            console.print(f"  • {key.rsplit(':', 1)[-1]}")
    else:
        console.print("live workers: none")


@app.command()
def audit(swarm: str = SwarmOpt) -> None:
    """Re-validate the whole ledger against the contract. Exit 1 on findings."""
    name = _swarm(swarm)
    report = audit_ledger(get_client(), ContractValidator(load_contract()), name)
    if report.ok:
        console.print(f"[green]✓[/green] {report.entries} entries, no findings")
        raise typer.Exit(0)
    table = Table(title=f"Audit findings — swarm '{name}' ({report.entries} entries)")
    table.add_column("seq")
    table.add_column("rule")
    table.add_column("detail")
    for f in report.findings:
        table.add_row(str(f.seq), f.rule, f.detail)
    console.print(table)
    raise typer.Exit(1)


@app.command()
def export(
    out: Path = typer.Option(..., "--out", help="Output JSONL path"),
    swarm: str = SwarmOpt,
) -> None:
    """Export the ledger as JSONL (fixtures, backups, incident capture)."""
    name = _swarm(swarm)
    count = export_jsonl(get_client(), name, out)
    console.print(f"[green]✓[/green] {count} entries → {out}")


@app.command()
def doctor(swarm: str = SwarmOpt) -> None:
    """Preflight checks: Redis reachable, AOF on, ledger audit clean."""
    name = _swarm(swarm)
    failures = 0
    try:
        client = get_client()
        client.ping()
        console.print("[green]✓[/green] redis reachable")
    except Exception as e:  # noqa: BLE001 — every failure is a finding here
        console.print(f"[red]✗[/red] redis unreachable: {e}")
        raise typer.Exit(1) from None

    appendonly = client.config_get("appendonly").get("appendonly")
    if appendonly == "yes":
        console.print("[green]✓[/green] AOF persistence on")
    else:
        console.print("[red]✗[/red] AOF is off — losing the ledger tail on power loss is a correctness bug")
        failures += 1

    report = audit_ledger(client, ContractValidator(load_contract()), name)
    if report.ok:
        console.print(f"[green]✓[/green] ledger audit clean ({report.entries} entries)")
    else:
        console.print(f"[red]✗[/red] ledger audit: {len(report.findings)} findings (run `relay audit`)")
        failures += 1

    raise typer.Exit(1 if failures else 0)


