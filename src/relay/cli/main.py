@app.command()
def destroy(
    swarm: str = SwarmOpt,
    force: bool = typer.Option(False, "--force", help="Skip the confirmation prompt"),
) -> None:
    """Remove every trace of a swarm: workers, ledger, Redis keys, local state.

    The project folder itself is untouched — delete it yourself if you want
    the code gone too. After destroy, `relay up` starts from a blank slate
    and `relay chat` begins a brand-new conversation.
    """
    import shutil

    from relay.cli import procs, redisctl

    name = _swarm(swarm)
    if not force and not typer.confirm(
        f"Erase swarm '{name}' completely (ledger, history, sessions)? This cannot be undone."
    ):
        raise typer.Exit(0)

    roles = list(procs.running_roles(name).items())
    if roles:
        console.print(f"stopping {len(roles)} worker(s)…")
        for role, pid in roles:
            console.print(f"  · {role} (pid {pid}) — waiting up to 3s for a clean exit…", end="")
            procs.stop_worker(name, role, timeout_s=3.0)  # a doomed swarm needs no grace
            console.print(" [green]stopped[/green]")
    else:
        console.print("no tracked workers running")
    strays = procs.reap_swarm(name)
    if strays:
        console.print(f"  · reaped {len(strays)} untracked worker(s): {', '.join(map(str, strays))}")

    console.print("deleting Redis keys (ledger, groups, claims)…", end="")
    deleted = redisctl.wipe_swarm_keys(get_client(), name)
    console.print(f" [green]{deleted} deleted[/green]")

    state = procs.state_root() / name
    if state.exists():
        console.print(f"removing {state} (logs, sessions, chat marker)…", end="")
        shutil.rmtree(state)
        console.print(" [green]done[/green]")
    console.print(f"[bold green]✓[/bold green] swarm '{name}' is gone — `relay up` starts from nothing")


@app.command()
def chat(
    swarm: str = SwarmOpt,
    new: bool = typer.Option(False, "--new", help="Start a fresh conversation instead of continuing"),
) -> None:
    """Open the Interpreter: a native Claude Code session wired to the swarm."""
    import os
    import tomllib

    from relay.bus import groups as groups_mod
    from relay.bus.keys import group_name, ledger_key
    from relay.cli import procs
    from relay.cli.context import find_project
    from relay.cli.profiles import settings_path, write_profiles

    project = find_project()
    name = _swarm(swarm)

    # mail must queue even while no session is open
    client = get_client()
    for role in ("interpreter", "owner"):
        groups_mod.ensure_group(client, ledger_key(name), group_name(role))
    write_profiles(project, name)  # keep hooks/permissions current

    from relay.cli.context import config_path

    config = tomllib.loads(config_path(project).read_text())
    interp_cfg = (config.get("roles") or {}).get("interpreter") or {}
    from relay.cli.entrypoints import relay_command
    from relay.contract import load_contract
    from relay.contract.cheatsheet import for_role

    playbook = (Path(__file__).resolve().parents[3] / "roles" / "interpreter.md").read_text()
    # absolute paths and the full vocabulary, because a session that has to
    # hunt for its own tools and payload shapes pays a whole context re-send
    # per search — measured at ~half the tool calls of a fresh scopa session
    system_prompt = playbook + NATIVE_SESSION_SUFFIX.format(
        swarm=name,
        send=relay_command("relay-send"),
        id=relay_command("relay-id"),
        inbox=relay_command("relay-inbox"),
    ) + for_role(load_contract(), "interpreter")

    marker = procs.state_root() / name / "interpreter" / "native-session"
    marker.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["claude",
           "--dangerously-skip-permissions",
           "--append-system-prompt", system_prompt,
           # the settings file still matters: it carries the relay-inbox hooks
           "--settings", str(settings_path(project, "interpreter")),
           "--model", str(interp_cfg.get("model") or "opus")]
    if marker.exists() and not new:
        cmd.append("--continue")
        kickoff = None
    else:
        marker.write_text("started")
        # leading '<' marks this as synthetic: the hook must NOT record it as
        # the owner's words, and the model must never block on --wait here
        kickoff = ("<relay-kickoff> Run `relay-inbox --swarm "
                   f"{name}` once (WITHOUT --wait — the Owner is about to type), "
                   "then introduce yourself in two sentences and ask for their "
                   "problem if none is pending.")
    if kickoff:
        cmd.append(kickoff)
    os.chdir(project)
    # execvpe carries the relay commands on PATH: the session's hooks and every
    # relay-send the Interpreter runs need them, and a login shell does not
    # read ~/.zshrc
    from relay.cli.entrypoints import env_with_entrypoints

    session_env = env_with_entrypoints()
    if not sys.stdin.isatty():
        os.execvpe("claude", cmd, session_env)      # piped/tested: nothing to wake

    # Otherwise relay stays in the middle, holding the session's input, so mail
    # that lands while the Interpreter is idle can knock on the door. Nothing
    # here reads what Claude Code prints — the trigger is a ledger event.
    from relay.cli import pty_proxy
    from relay.cli.wake import (
        NUDGE_COOLDOWN_S,
        next_keystroke,
        undelivered_for_interpreter,
    )

    state = {"checked": 0.0, "typed": -NUDGE_COOLDOWN_S, "returns": 0.0}

    def knock(quiet_for_s: float) -> str | None:
        now = time.monotonic()
        if now - state["checked"] < 2.0:            # the ledger is cheap, not free
            return None
        state["checked"] = now
        try:
            waiting = undelivered_for_interpreter(client, name)
        except Exception:                            # never take the session down
            return None
        if not waiting:                              # collected: start clean next time
            state["returns"] = 0.0
            return None
        keystroke = next_keystroke(
            waiting=waiting, swarm=name, quiet_for_s=quiet_for_s,
            since_last_nudge_s=now - state["typed"], returns_sent=int(state["returns"]),
        )
        if keystroke is None:
            return None
        state["typed"] = now
        state["returns"] += 1
        return keystroke

    raise typer.Exit(pty_proxy.run(cmd, session_env, on_idle=knock))


@app.command()
def watch(
    swarm: str = SwarmOpt,
    events: bool = typer.Option(False, "--events",
                                help="Event log: every ledger event from the start, as a table"),
    tokens: bool = typer.Option(False, "--tokens",
                                help="Token burn: spend per role and per turn, as it happens"),
) -> None:
    """Live board: assistant liveness, behaviour states, event feed.

    With --events: the full audited history instead — timestamp, producer,
    type, work-item ref, payload — scrollback-friendly.

    With --tokens: what the swarm is spending, folded from the ledger as it
    lands — per role (with the model that actually billed, and how many turns
    started cold), the running rate, cache warmth, and the last turns as they
    complete. Same arithmetic as `relay costs`, live.

    All three views follow; Ctrl-C stops.
    """
    from relay.cli.watch import events_view, tokens_view
    from relay.cli.watch import watch as watch_loop

    if events and tokens:
        console.print("[red]✗[/red] --events and --tokens are different views: pick one")
        raise typer.Exit(1)
    try:
        if tokens:
            tokens_view(_swarm(swarm))
        elif events:
            events_view(_swarm(swarm))
        else:
            watch_loop(_swarm(swarm))
    except KeyboardInterrupt:
        pass


