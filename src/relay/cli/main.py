# ── project initialization (also invoked automatically by `relay up`) ────────

def _initialize(project: Path, swarm: str, test_command: str) -> None:
    from relay.cli.profiles import write_profiles

    if sp.run(["git", "rev-parse", "--git-dir"], cwd=project, capture_output=True).returncode != 0:
        sp.run(["git", "init", "-q", "-b", "main"], cwd=project, check=True)
        console.print("[green]✓[/green] git repository initialized")
    gitignore = project / ".gitignore"
    marker = ".relay/"
    if not gitignore.exists() or marker not in gitignore.read_text():
        with gitignore.open("a") as f:
            f.write(f"\n# relay swarm runtime state\n{marker}\n")
        console.print(f"[green]✓[/green] added {marker} to .gitignore")
    if sp.run(["git", "rev-parse", "HEAD"], cwd=project, capture_output=True).returncode != 0:
        sp.run(["git", "add", "-A"], cwd=project, check=True)
        sp.run(["git", "commit", "-qm", "Initial commit (relay init)"], cwd=project, check=True)
        console.print("[green]✓[/green] initial commit created")

    profiles = write_profiles(project, swarm)
    console.print(f"[green]✓[/green] {len(profiles)} permission profiles → {profiles[0].parent}")

    gates_src = Path(__file__).resolve().parents[3] / "policies" / "gates.yaml"
    gates_dst = project / ".relay" / "gates.yaml"
    if gates_src.exists() and not gates_dst.exists():
        gates_dst.parent.mkdir(parents=True, exist_ok=True)
        gates_dst.write_text(gates_src.read_text())
        console.print(f"[green]✓[/green] gate policy → {gates_dst}")

    from relay.cli.context import has_config

    if has_config(project):
        return
    config = project / ".relay" / "relay.toml"
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text(
        "# Relay swarm configuration for this project\n"
        f"# generated by relay {__version__}\n\n"
        "[swarm]\n"
        f'name = "{swarm}"\n\n'
        "[commands]\n"
        f'acceptance_test = "{test_command}"\n'
        '# suite = "uv run pytest -q"\n\n'
        "[ui]\n"
        'terminal = "iterm"   # window app for `relay up --windows`: iterm | terminal\n\n'
        "[roles.interpreter]\n"
        'runner = "claude"\nmodel = "opus"\n\n'
        "[roles.analyst]\n"
        'runner = "claude"\n\n'
        "[roles.specifier]\n"
        'runner = "claude"\n\n'
        "[roles.builder]\n"
        'runner = "claude"\n'
    )
    console.print(f"[green]✓[/green] wrote {config}")


@app.command()
def init(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    test_command: str = typer.Option(
        "uv run pytest -q {test_paths}", "--test-command",
        help="How the toolgate runs acceptance tests (use {test_paths})",
    ),
) -> None:
    """Prepare a project without starting it (relay up does this automatically)."""
    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    _initialize(project, swarm or project.name, test_command)


# ── runtime ───────────────────────────────────────────────────────────────────

@app.command()
def up(
    folder: Path = typer.Argument(Path("."), help="Project directory"),
    swarm: str = SwarmOpt,
    roles: str = typer.Option("", "--roles", help="Comma-separated subset (default: all Phase-1 roles)"),
    tmux: bool = typer.Option(False, "--tmux", help="Open a tmux session: watch + per-role tails"),
    windows: bool = typer.Option(False, "--windows",
                                 help="Open one Terminal window per assistant (live activity) + watch"),
) -> None:
    """Start the swarm for a project (initializing it on first run)."""
    from relay.cli import procs, redisctl

    project = folder.expanduser().resolve()
    if not project.is_dir():
        console.print(f"[red]✗[/red] not a directory: {project}")
        raise typer.Exit(1)
    from relay.cli.context import has_config

    legacy_config = project / "relay.toml"
    if legacy_config.is_file() and not (project / ".relay" / "relay.toml").exists():
        (project / ".relay").mkdir(exist_ok=True)
        legacy_config.rename(project / ".relay" / "relay.toml")
        console.print("[green]✓[/green] moved relay.toml → .relay/relay.toml (root stays clean)")
    if not has_config(project):
        _initialize(project, swarm or project.name, "uv run pytest -q {test_paths}")
    name = swarm or swarm_name(project)

    from relay.bus import groups as groups_mod
    from relay.bus.keys import group_name, ledger_key
    from relay.cli.profiles import write_profiles

    console.print(f"[green]✓[/green] {redisctl.ensure_running(procs.state_root())}")
    if not _claim_swarm(name, project):
        raise typer.Exit(1)
    write_profiles(project, name)  # keep permission profiles + hooks current
    for role in ("interpreter", "owner"):  # interpreter mail queues even before chat opens
        groups_mod.ensure_group(get_client(), ledger_key(name), group_name(role))
    selected = [r.strip() for r in roles.split(",") if r.strip()]
    if not selected:
        from relay.coordinator.policy import Policy
        from relay.workers.run import resolve_policy_path

        selected = list(procs.PHASE1_ROLES)
        policy_path = resolve_policy_path(project)
        if policy_path is not None:
            policy = Policy.load(policy_path)
            for spec in (*policy.per_behaviour, *policy.per_story, *policy.per_iteration):
                if spec.role not in selected:
                    selected.append(spec.role)
    for role in selected:
        pid = procs.start_worker(name, role, project)
        console.print(f"[green]✓[/green] {role} (pid {pid})")
    console.print(f"\nswarm '[bold]{name}[/bold]' is up — next, in this folder:")
    console.print("  relay chat     (terminal 1 — talk to the swarm)")
    console.print("  relay watch    (terminal 2 — live board)")
    if tmux:
        _open_tmux(name, selected)
    if windows:
        import tomllib

        from relay.cli.context import config_path

        ui_cfg = tomllib.loads(config_path(project).read_text()).get("ui") or {}
        _open_windows(name, selected, terminal=str(ui_cfg.get("terminal", "iterm")))


def _claim_swarm(name: str, project: Path) -> bool:
    """Two folders with the same basename must not share a ledger: a swarm
    name belongs to exactly one project directory."""
    from relay.bus.keys import project_key

    client = get_client()
    raw_owner = client.get(project_key(name))
    owner = raw_owner.decode() if isinstance(raw_owner, bytes) else raw_owner
    if owner and str(owner) != str(project):
        console.print(
            f"[red]✗[/red] swarm '{name}' already belongs to {owner}.\n"
            f"  Give this project its own name:  relay up . --swarm {name}-2\n"
            f"  (or set it permanently under [swarm] name in relay.toml)"
        )
        return False
    client.set(project_key(name), str(project))
    return True


def _open_windows(name: str, roles: list[str], terminal: str = "iterm") -> None:
    """One read-only viewer window per assistant + one mission-control watch.

    Viewers only: they follow logs and the stream, deliver nothing, and can be
    closed at any time without affecting the swarm. The terminal app comes
    from [ui] terminal in relay.toml — iTerm by default.
    """
    import platform

    import shutil as _shutil

    if platform.system() != "Darwin":
        console.print("[yellow]•[/yellow] --windows is macOS-only — use --tmux here")
        return
    # iTerm runs the command DIRECTLY (no shell, bare launchd PATH), so use the
    # absolute relay path and wrap in a login shell for the user's environment
    relay_bin = _shutil.which("relay") or "relay"
    commands = [f"{relay_bin} watch --swarm {name}"] + [
        f"{relay_bin} tail {r} --swarm {name}" for r in roles
    ]

    def _iterm(command: str) -> bool:
        shell_command = f"/bin/zsh -lc '{command}'"
        script = (f'tell application "iTerm"\n'
                  f'  create window with default profile command "{shell_command}"\n'
                  f'end tell')
        return sp.run(["osascript", "-e", script], capture_output=True).returncode == 0

    def _terminal_app(command: str) -> bool:
        return sp.run(["osascript", "-e",
                       f'tell application "Terminal" to do script "{command}"'],
                      capture_output=True).returncode == 0

    open_one = _iterm if terminal.lower() in ("iterm", "iterm2") else _terminal_app
    app_name = "iTerm" if open_one is _iterm else "Terminal"
    opened = 0
    for command in commands:
        if not open_one(command):
            if open_one is _iterm:  # iTerm missing/unscriptable → fall back once, loudly
                console.print("[yellow]•[/yellow] iTerm not reachable — falling back to Terminal.app "
                              '(set [ui] terminal = "terminal" in relay.toml to silence this)')
                open_one, app_name = _terminal_app, "Terminal"
                if open_one(command):
                    opened += 1
                continue
        else:
            opened += 1
    sp.run(["osascript", "-e", f'tell application "{app_name}" to activate'], capture_output=True)
    console.print(f"[green]✓[/green] {opened} {app_name} windows opened (read-only viewers)")


def _open_tmux(name: str, roles: list[str]) -> None:
    import shutil as _shutil

    if _shutil.which("tmux") is None:
        console.print("[yellow]•[/yellow] tmux not installed — skipping --tmux")
        return
    session = f"relay-{name}"
    sp.run(["tmux", "kill-session", "-t", session], capture_output=True)
    sp.run(["tmux", "new-session", "-d", "-s", session, "-n", "watch",
            f"relay watch --swarm {name}"], check=True)
    sp.run(["tmux", "set-option", "-t", session, "mouse", "on"], capture_output=True)
    for role in roles:
        sp.run(["tmux", "new-window", "-t", session, "-n", role,
                f"relay tail {role} --swarm {name}"], check=True)
    sp.run(["tmux", "select-window", "-t", f"{session}:watch"], capture_output=True)
    console.print(f"[green]✓[/green] tmux session ready (mouse on):  tmux attach -t {session}")


@app.command()
def down(swarm: str = SwarmOpt) -> None:
    """Stop the enclosing project's swarm (the ledger keeps everything)."""
    from relay.cli import procs

    name = _swarm(swarm)
    stopped = False
    for role in list(procs.running_roles(name)) or list(procs.PHASE1_ROLES):
        if procs.stop_worker(name, role):
            console.print(f"[green]✓[/green] {role} stopped")
            stopped = True
    strays = procs.reap_swarm(name)  # zombies with no pidfile (deleted state dirs)
    if strays:
        console.print(f"[yellow]•[/yellow] reaped {len(strays)} untracked worker(s): "
                      f"{', '.join(map(str, strays))}")
    if stopped or strays:
        console.print(f"swarm '{name}' is down — `relay up` resumes exactly here")


NATIVE_SESSION_SUFFIX = """

== Session mode ==
You are the Interpreter, running as THIS Claude Code session. The human
talking to you here is the Owner. Speak to them directly — that is your
voice. Everything for the Analyst or the Coordinator goes through relay-send
on the bus; your terminal text is not work product for them.

Relay mail (analyst questions, checkpoints, escalations) reaches you
automatically: it is injected when you finish a turn and alongside whatever
the Owner types. When you have just dispatched work downstream and expect a
reply (e.g. after analysis.requested), do not end your turn in silence —
run `relay-inbox --swarm {swarm} --wait 240` to wait for the reply, then
brief the Owner on what arrived. Check `relay-inbox --swarm {swarm}` at the
start of the conversation for anything already waiting.

The Owner's words are recorded on the ledger automatically — never re-post
them. Mint ids with `relay-id q` / `relay-id gate`. Never leave the Owner
without a response.
"""


@app.command()
def destroy(
    swarm: str = SwarmOpt,
    force: bool = typer.Option(False, "--force", help="Skip the confirmation prompt"),
) -> None:
    """Remove every trace of a swarm: workers, ledger, Redis keys, local state.

    The project folder itself is untouched — delete it yourself if you want
    the code gone too. After destroy, `relay up` starts from a blank slate
    and `relay chat` begins a brand-new conversation.
    """
    import shutil

    from relay.cli import procs, redisctl

    name = _swarm(swarm)
    if not force and not typer.confirm(
        f"Erase swarm '{name}' completely (ledger, history, sessions)? This cannot be undone."
    ):
        raise typer.Exit(0)

    roles = list(procs.running_roles(name).items())
    if roles:
        console.print(f"stopping {len(roles)} worker(s)…")
        for role, pid in roles:
            console.print(f"  · {role} (pid {pid}) — waiting up to 3s for a clean exit…", end="")
            procs.stop_worker(name, role, timeout_s=3.0)  # a doomed swarm needs no grace
            console.print(" [green]stopped[/green]")
    else:
        console.print("no tracked workers running")
    strays = procs.reap_swarm(name)
    if strays:
        console.print(f"  · reaped {len(strays)} untracked worker(s): {', '.join(map(str, strays))}")

    console.print("deleting Redis keys (ledger, groups, claims)…", end="")
    deleted = redisctl.wipe_swarm_keys(get_client(), name)
    console.print(f" [green]{deleted} deleted[/green]")

    state = procs.state_root() / name
    if state.exists():
        console.print(f"removing {state} (logs, sessions, chat marker)…", end="")
        shutil.rmtree(state)
        console.print(" [green]done[/green]")
    console.print(f"[bold green]✓[/bold green] swarm '{name}' is gone — `relay up` starts from nothing")


@app.command()
def chat(
    swarm: str = SwarmOpt,
    new: bool = typer.Option(False, "--new", help="Start a fresh conversation instead of continuing"),
) -> None:
    """Open the Interpreter: a native Claude Code session wired to the swarm."""
    import os
    import tomllib

    from relay.bus import groups as groups_mod
    from relay.bus.keys import group_name, ledger_key
    from relay.cli import procs
    from relay.cli.context import find_project
    from relay.cli.profiles import settings_path, write_profiles

    project = find_project()
    name = _swarm(swarm)

    # mail must queue even while no session is open
    client = get_client()
    for role in ("interpreter", "owner"):
        groups_mod.ensure_group(client, ledger_key(name), group_name(role))
    write_profiles(project, name)  # keep hooks/permissions current

    from relay.cli.context import config_path

    config = tomllib.loads(config_path(project).read_text())
    interp_cfg = (config.get("roles") or {}).get("interpreter") or {}
    playbook = (Path(__file__).resolve().parents[3] / "roles" / "interpreter.md").read_text()
    system_prompt = playbook + NATIVE_SESSION_SUFFIX.format(swarm=name)

    marker = procs.state_root() / name / "interpreter" / "native-session"
    marker.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["claude",
           "--dangerously-skip-permissions",
           "--append-system-prompt", system_prompt,
           # the settings file still matters: it carries the relay-inbox hooks
           "--settings", str(settings_path(project, "interpreter")),
           "--model", str(interp_cfg.get("model") or "opus")]
    if marker.exists() and not new:
        cmd.append("--continue")
        kickoff = None
    else:
        marker.write_text("started")
        kickoff = ("Introduce yourself to the Owner in two sentences, check "
                   f"`relay-inbox --swarm {name}` for anything already waiting, "
                   "and ask for their problem if there is none.")
    if kickoff:
        cmd.append(kickoff)
    os.chdir(project)
    os.execvp("claude", cmd)


